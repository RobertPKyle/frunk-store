// Writes apps/mahjong/glyphs.js: the Chinese characters on the tiles and the
// claim buttons, as SVG outlines from LXGW WenKai TC Medium (OFL-1.1). A tile
// face drawn as a background image can't use the page's fonts, and a car may
// have no Chinese font at all, so the outlines travel with the app.
//
//   npm run build:mahjong
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const VERSION = 'v1.530';
const FILE = 'LXGWWenKaiTC-Medium.ttf';
const URL_ = `https://github.com/lxgw/LxgwWenkaiTC/releases/download/${VERSION}/${FILE}`;
const SHA256 = '649efd8516f42d36eacc05480d5dbd2713fb28fbd2bbee8ea76fc40875045c49';

// Tiles, then the buttons and the setup screen's tiles
const CHARS = '一二三四五六七八九萬東南西北中發春夏秋冬梅蘭菊竹' + '碰吃上槓杠胡糊過过麻雀將将';

const cache = fileURLToPath(new URL('./.mahjong-build/', import.meta.url));
const out = fileURLToPath(new URL('../apps/mahjong/glyphs.js', import.meta.url));
mkdirSync(cache, { recursive: true });

const path = cache + FILE;
if (!existsSync(path)) {
  const res = await fetch(URL_);
  if (!res.ok) throw new Error(`${URL_}: HTTP ${res.status}`);
  writeFileSync(path, Buffer.from(await res.arrayBuffer()));
}
const bytes = readFileSync(path);
const sha = createHash('sha256').update(bytes).digest('hex');
if (SHA256 && sha !== SHA256) throw new Error(`${FILE}: SHA-256 is ${sha}, expected ${SHA256}`);

const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const SIZE = 100;   // each glyph sits in a 100 by 100 box
const entries = [...new Set(CHARS)].map(ch => {
  const glyph = font.charToGlyph(ch);
  if (!glyph.index) throw new Error(`no glyph for ${ch}`);
  // the em box, centered on its baseline offset, keeps the characters' sizes in proportion
  const d = glyph.getPath(0, 88, SIZE).toPathData(1);
  return `  '${ch}': '${d}',`;
});
writeFileSync(out, `// Generated by tools/build-mahjong.mjs from LXGW WenKai TC Medium ${VERSION}
// (OFL-1.1, see NOTICE). Outlines in a 100 by 100 box.
export const GLYPHS = {
${entries.join('\n')}
};
`);
console.log(`${entries.length} glyphs, font SHA-256 ${sha}`);
